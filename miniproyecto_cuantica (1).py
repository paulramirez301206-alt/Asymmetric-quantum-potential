## PULSO GAUSSIANO

b = 0.3
x0_pos = 0.4
v0 = 6.0
p0 = m * v0


A_norm = (2.0 / (np.pi * b**2))**0.25

def psi0_real(x):
    return A_norm * np.exp(-(x - x0_pos)**2 / b**2) * np.cos(p0 * x / h)

def psi0_imag(x):
    return A_norm * np.exp(-(x - x0_pos)**2 / b**2) * np.sin(p0 * x / h)


c_n = []
for n in range(N):
    z_val = roots_z[n]
    re, _ = quad(lambda x: phi_n(x, z_val) * psi0_real(x), -2, 4)
    im, _ = quad(lambda x: phi_n(x, z_val) * psi0_imag(x), -2, 4)
    c_n.append(re + 1j * im)

c_n = np.array(c_n)
c_n /= np.sqrt(np.sum(np.abs(c_n)**2))

Nx = 400
Nt = 250
x_grid = np.linspace(-0.5, 2.5, Nx)
dx = x_grid[1] - x_grid[0]
t_grid = np.linspace(0, 1.2, Nt)

phi_matrix = np.zeros((N, Nx))
for n in range(N):
    phi_matrix[n, :] = [phi_n(x, roots_z[n]) for x in x_grid]


density_map = np.zeros((Nt, Nx))
x_expected = np.zeros(Nt)

for it, t in enumerate(t_grid):
    phases = np.exp(-1j * E_n * t / h)
    psi_t = np.dot(c_n * phases, phi_matrix)
    prob = np.abs(psi_t)**2
    density_map[it, :] = prob
    x_expected[it] = np.sum(x_grid * prob) * dx


fig, axes = plt.subplots(1, 2, figsize=(14, 5))

#Mapa Bidimensional Espacio-Temporal de Densidad
im = axes[0].pcolormesh(x_grid, t_grid, density_map, shading='auto', cmap='viridis')
axes[0].axvline(0, color='cyan', linestyle='--', linewidth=1.5, label='Pared $U_1=85$')
axes[0].axvline(L, color='magenta', linestyle='--', linewidth=1.5, label='Pared $U_2=170$')
axes[0].set_xlabel('Posicion $x$', fontsize=11)
axes[0].set_ylabel('Tiempo $t$', fontsize=11)
axes[0].set_title('Densidad de Probabilidad $|\Psi(x,t)|^2$', fontsize=12)
axes[0].legend(loc='upper right')
fig.colorbar(im, ax=axes[0], label='$|\Psi(x,t)|^2$')

#  <x>(t)
axes[1].plot(t_grid, x_expected, 'b-', linewidth=2, label=r'$\langle x \rangle(t)$')
axes[1].axhline(0, color='r', linestyle='--', alpha=0.7, label='Pared izquierda ($x=0$)')
axes[1].axhline(L, color='g', linestyle='--', alpha=0.7, label='Pared derecha ($x=2$)')
axes[1].set_xlabel('Tiempo $t$', fontsize=11)
axes[1].set_ylabel(r'Posicion Media $\langle x \rangle$', fontsize=11)
axes[1].set_title(r'Evolucion del Valor Esperado de la Posicion $\langle x \rangle(t)$', fontsize=12)
axes[1].grid(True, linestyle='--', alpha=0.5)
axes[1].legend(loc='upper right')

plt.tight_layout()
plt.show()
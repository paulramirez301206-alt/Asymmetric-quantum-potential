def ecuacion_caracteristica(z, n):
    term1 = np.arctan(np.sqrt(z0**2 - z**2) / z)
    term2 = np.arctan(np.sqrt(c * z0**2 - z**2) / z)
    return z - n * np.pi - term1 - term2

print(f"{'Estado (n)':<12} | {'Raíz z_n':<12} | {'Energía E_n':<14} | {'E_n / U1 (%)':<12}")
print("-" * 58)

for n in range(N):

    z_min = max(1e-5, n * np.pi + 1e-5)
    z_max = min(z0 - 1e-5, (n + 1) * np.pi - 1e-5)


    sol = root_scalar(ecuacion_caracteristica, args=(n,), bracket=[z_min, z_max], method='brentq')
    zn = sol.root


    En = zn**2 / np.pi**2

    print(f"{n:<12} | {zn:<12.6f} | {En:<14.6f} | {En / U1 * 100:<11.2f}%")


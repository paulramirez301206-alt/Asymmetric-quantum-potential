import numpy as np
import matplotlib.pyplot as plt
from scipy.optimize import root_scalar
from scipy.integrate import quad

# PARAMETROS
h=1.0
m = np.pi**2 / 8.0
U1 = 85.0
c = 2.0
U2 = c * U1
L=2.0

# Parametro adimensional
z0 = np.sqrt(2 * m * U1) * L / h

#Conteo de ESTADOS
X = (z0 - np.arctan(np.sqrt(c - 1))) / np.pi
N = int(np.ceil(X))




#CALCULO DE RAICES z_n
def eq_z(z, n):
    term1 = np.arctan(np.sqrt(z0**2 - z**2) / z)
    term2 = np.arctan(np.sqrt(c * z0**2 - z**2) / z)
    return z - n * np.pi - term1 - term2

roots_z = []
for n in range(N):
    z_min = max(1e-5, n * np.pi + 1e-5)
    z_max = min(z0 - 1e-5, (n + 1) * np.pi - 1e-5)
    sol = root_scalar(eq_z, args=(n,), bracket=[z_min, z_max], method='brentq')
    roots_z.append(sol.root)

roots_z = np.array(roots_z)
E_n = roots_z**2 / np.pi**2


# FUNCION DE ONDA NORMALIZADA!!
def phi_n(x, z):
    k = z / L
    k1 = np.sqrt(z0**2 - z**2) / L
    k2 = np.sqrt(c * z0**2 - z**2) / L

    L_eff = L + 1.0/k1 + 1.0/k2

    A1 = np.sqrt(2.0 / L_eff) * (z / z0)
    B = A1 * (k1 / k)
    C = A1
    A3 = B * np.sin(k * L) + C * np.cos(k * L)

    if x < 0:
        return A1 * np.exp(k1 * x)
    elif x <= L:
        return B * np.sin(k * x) + C * np.cos(k * x)
    else:
        return A3 * np.exp(-k2 * (x - L))

phi_v = np.vectorize(phi_n, excluded=['z'])

# EIGENESTADOS
x_grid = np.linspace(-1.0, 3.0, 1000)

plt.figure(figsize=(10, 8))

V_grid = np.where(x_grid < 0, U1, np.where(x_grid <= L, 0, U2))
plt.plot(x_grid, V_grid, 'k-', linewidth=2.5, label='Potencial $V(x)$')

#graficar cada estado ligado
scale = 3.0 #Factor de escala
colors = plt.cm.plasma(np.linspace(0.1, 0.9, N))

for n in range(N):
    psi = phi_v(x_grid, z=roots_z[n])
    plt.plot(x_grid, E_n[n] + scale * psi, color=colors[n], linewidth=1.5,
             label=f'$n={n}, E_{n}={E_n[n]:.2f}$')
    plt.axhline(E_n[n], color=colors[n], linestyle=':', alpha=0.5)

plt.xlim(-0.8, 2.8)
plt.ylim(-5, U2 + 10)
plt.xlabel('Posicion ($x$)', fontsize=12)
plt.ylabel('Energia ($E$)', fontsize=12)
plt.title('Eigenestados del Pozo de Pontencial Asimetrico ($U_1=85, U_2=170$)', fontsize=14)
plt.legend(loc='upper right', bbox_to_anchor=(1.3, 1.0), fontsize=9)
plt.grid(True, linestyle='--', alpha=0.4)
plt.tight_layout()
plt.show()

